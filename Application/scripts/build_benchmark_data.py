"""Writes src/plantcare/data/benchmark.ts from the benchmark results
(New_Models_Baselines/03_Benchmark_Suite/results/summary_*.csv).

Run from Application/ after re-running the benchmark:  python scripts/build_benchmark_data.py
"""
import json
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.abspath(os.path.join(HERE, '..', '..', 'New_Models_Baselines', '03_Benchmark_Suite', 'results'))
OUT = os.path.abspath(os.path.join(HERE, '..', 'src', 'plantcare', 'data', 'benchmark.ts'))

SHOW = ['CNN EfficientNet-B0 (frozen) + LR', 'CNN MobileNetV3-Large (frozen) + LR', 'Extra Trees (tuned)', 'LightGBM',
        'Gradient Boosting (HistGB, tuned)', 'XGBoost', 'RBF SVM (tuned)', 'WL + SVM', 'WL + SVM (tuned)',
        'Random Forest', 'Logistic Regression', 'Always says "stressed" (reference)']
NICE = {'CNN EfficientNet-B0 (frozen) + LR': 'CNN EfficientNet-B0 (frozen)',
        'CNN MobileNetV3-Large (frozen) + LR': 'CNN MobileNetV3 (frozen)',
        'Gradient Boosting (HistGB, tuned)': 'Gradient Boosting (tuned)',
        'WL + SVM': 'WL + SVM (best setting)', 'WL + SVM (tuned)': 'WL + SVM (tuned, fair)',
        'Random Forest': 'Random Forest (default)', 'Logistic Regression': 'Logistic Regression (default)',
        'Always says "stressed" (reference)': 'Always answers "stressed"'}


def kind(m):
    return 'ours' if m.startswith('WL') else 'cnn' if m.startswith('CNN') else 'reference' if m.startswith('Always') else 'baseline'


def r(v, d=4):
    return None if pd.isna(v) else round(float(v), d)


l3 = pd.read_csv(os.path.join(RES, 'summary_level3.csv')).set_index('Model')
rob = pd.read_csv(os.path.join(RES, 'summary_robustness_level1.csv')).set_index('Model')
level3 = [{'model': NICE.get(m, m), 'kind': kind(m), 'macroF1': r(l3.loc[m, 'Macro-F1']),
           'balancedAccuracy': r(l3.loc[m, 'Balanced acc.']), 'accuracy': r(l3.loc[m, 'Accuracy']),
           'healthyFound': r(l3.loc[m, 'Specificity (healthy found)']),
           'cropIdentified': r(l3.loc[m].get('Crop identified correctly')),
           'msPerPhoto': r(l3.loc[m].get('End-to-end ms/photo'), 0)} for m in SHOW if m in l3.index]
robust = [{'model': NICE.get(m, m), 'kind': kind(m), 'clean': r(rob.loc[m, 'Clean macro-F1']),
           'change': r(rob.loc[m, 'Mean F1 change'])} for m in SHOW if m in rob.index]
data = {'level3': level3, 'robustness': sorted(robust, key=lambda x: -x['change'])}
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/build_benchmark_data.py from New_Models_Baselines/03_Benchmark_Suite results.\n')
    f.write('export const BENCHMARK = ' + json.dumps(data, indent=1) + ' as const;\n')
print('wrote', OUT, len(level3), 'level-3 rows,', len(robust), 'robustness rows')
